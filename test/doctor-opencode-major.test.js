'use strict';

// After an OpenCode upgrade to 2.x, a guard plugin generated before 0.12.2 is
// silently ignored: OpenCode reports a failed plugin and the user believes they
// are covered. `doctor` reads `opencode --version` (and nothing else) to tell the
// two cases apart: a stale plugin is a warning on 1.x, a missing guard on 2.x.

const { test } = require('node:test');
const assert = require('node:assert');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const CLI = path.join(__dirname, '..', 'bin', 'ai-flow.js');
const PLUGIN = path.join('.opencode', 'plugins', 'coding-flow-guard.js');
const V1_ONLY = '// coding-flow:guard-plugin v0.12.1 — generated by `ai-flow init`/`upgrade`; edit freely by removing this line\nexport const CodingFlowGuard = async () => ({});\n';

// `output` is what the fake `opencode --version` prints; null means no binary.
// The fake logs every invocation, so a test can prove `--version` is the only one.
function setup(t, output, { globalPlugin = null, exit = 0, stream = 'stdout' } = {}) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'coding-flow-ocmajor-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const bin = path.join(root, 'bin');
  const project = path.join(root, 'project');
  const xdg = path.join(root, 'xdg');
  fs.mkdirSync(bin);
  fs.mkdirSync(project);
  if (output !== null) {
    fs.writeFileSync(path.join(bin, 'opencode'), `#!/bin/sh\necho "$@" >> "${root}/calls.log"\necho "${output}"${stream === 'stderr' ? ' >&2' : ''}\nexit ${exit}\n`, { mode: 0o755 });
  }
  if (globalPlugin !== null) {
    fs.mkdirSync(path.join(xdg, 'opencode', 'plugins'), { recursive: true });
    fs.writeFileSync(path.join(xdg, 'opencode', 'plugins', 'coding-flow-guard.js'), globalPlugin);
  }
  const env = { ...process.env, PATH: bin, XDG_CONFIG_HOME: xdg, CLAUDE_CONFIG_DIR: path.join(root, '.no-claude'), CLAUDE_PLUGIN_ROOT: '' };
  delete env.CLAUDECODE;
  delete env.OPENCODE;
  const run = (args) => {
    const res = spawnSync(process.execPath, [CLI, ...args], { cwd: project, env, encoding: 'utf8' });
    return { code: res.status, output: `${res.stdout}${res.stderr}` };
  };
  assert.equal(run(['init', '--opencode']).code, 0);
  return { run, project, calls: () => (fs.existsSync(path.join(root, 'calls.log')) ? fs.readFileSync(path.join(root, 'calls.log'), 'utf8') : '') };
}

test('2.x host + a plugin from before the 2.x entry: the guard is reported as not loaded, and doctor fails', (t) => {
  const { run, project, calls } = setup(t, '2.0.30');
  fs.writeFileSync(path.join(project, PLUGIN), V1_ONLY);

  const res = run(['doctor']);
  assert.notEqual(res.code, 0);
  assert.match(res.output, /guard is not loaded on OpenCode 2/);
  assert.match(res.output, /ai-flow upgrade/);
  assert.equal(calls().trim(), '--version', '--version is the only invocation');
});

test('2.x host + a current plugin: the guard line is fine', (t) => {
  const { run } = setup(t, '2.0.30');
  const res = run(['doctor']);
  assert.equal(res.code, 0, res.output);
  assert.doesNotMatch(res.output, /not loaded/);
});

test('1.x host + a plugin from before the 2.x entry: the existing stale warning, not the failure', (t) => {
  const { run, project } = setup(t, '1.19.0');
  fs.writeFileSync(path.join(project, PLUGIN), V1_ONLY);

  const res = run(['doctor']);
  assert.equal(res.code, 0, res.output);
  assert.match(res.output, /guard plugin does not match this install/);
  assert.doesNotMatch(res.output, /not loaded/);
});

test('no opencode binary: one informational line, no failure', (t) => {
  const { run, project } = setup(t, null);
  fs.writeFileSync(path.join(project, PLUGIN), V1_ONLY);

  const res = run(['doctor']);
  assert.equal(res.code, 0, res.output);
  assert.match(res.output, /`opencode` is not on PATH/);
  assert.doesNotMatch(res.output, /not loaded/);
});

test('every --version format parses; anything else counts as 1.x', (t) => {
  for (const [printed, fails] of [['opencode 2.0.30', true], ['v2.1.0', true], ['2.0.30', true], ['dev-build', false], ['', false]]) {
    const { run, project } = setup(t, printed);
    fs.writeFileSync(path.join(project, PLUGIN), V1_ONLY);
    const res = run(['doctor']);
    assert.equal(res.code !== 0, fails, `"${printed}": ${res.output}`);
  }
});

test('2.x host + a global plugin without the 2.x entry points at upgrade --global', (t) => {
  const { run } = setup(t, '2.0.30', { globalPlugin: V1_ONLY });
  const res = run(['doctor']);
  assert.notEqual(res.code, 0);
  assert.match(res.output, /global guard is not loaded on OpenCode 2/);
  assert.match(res.output, /ai-flow upgrade --global/);
});

test('a binary that prints its version on stderr is still read as 2.x', (t) => {
  const { run, project } = setup(t, '2.0.30', { stream: 'stderr' });
  fs.writeFileSync(path.join(project, PLUGIN), V1_ONLY);
  const res = run(['doctor']);
  assert.notEqual(res.code, 0);
  assert.match(res.output, /guard is not loaded on OpenCode 2/);
});

test('a binary that exits non-zero is found: no "not on PATH" note', (t) => {
  const { run, project } = setup(t, 'boom', { exit: 1 });
  fs.writeFileSync(path.join(project, PLUGIN), V1_ONLY);
  const res = run(['doctor']);
  assert.equal(res.code, 0, res.output);
  assert.doesNotMatch(res.output, /not on PATH/);
});

"use strict";

// `epics/INDEX.md`: the one file that remembers every epic once its directory
// has left the checkout (epic 17). This module owns its archived section, which
// is append-only — nothing on disk could regenerate it. Each entry's heading
// carries `<!-- coding-flow:archived NN slug -->`, the marker idempotence and
// numbering (story 17-03) read back. A hand-written INDEX.md is never rewritten:
// the section is appended after whatever is already there.

const fs = require("fs");
const path = require("path");

const INDEX_FILE = path.join("epics", "INDEX.md");
const SECTION_MARKER = "<!-- coding-flow:archived-section -->";
// The number is `-` for an epic directory that carries none (`epic-misc`).
const ENTRY_MARKER = /<!-- coding-flow:archived (\d+|-) ([^\s]+) -->/g;

const SECTION_HEADER = [
  "## Archived epics",
  "",
  SECTION_MARKER,
  "",
  "Written by `ai-flow archive`, append-only. Each entry names the commit where",
  "the epic's text still exists and the command that brings it back.",
  "",
].join("\n");

function indexPath(root) {
  return path.join(root, INDEX_FILE);
}

// "absent", "file", "symlink" or "other", without following a link: a
// symlinked INDEX.md would make a write land outside the repository.
function indexKind(root) {
  let stat;
  try {
    stat = fs.lstatSync(indexPath(root));
  } catch {
    return "absent";
  }
  if (stat.isSymbolicLink()) return "symlink";
  return stat.isFile() ? "file" : "other";
}

function readIndex(root) {
  return indexKind(root) === "file" ? fs.readFileSync(indexPath(root), "utf8") : null;
}

// Every archived entry as { number, slug }, in file order.
function archivedEpics(root) {
  const text = readIndex(root) || "";
  return [...text.matchAll(ENTRY_MARKER)].map((match) => ({ number: match[1], slug: match[2] }));
}

// `epic-08-evidence-levels` → { number: "08", slug: "evidence-levels" }; a
// directory without a number keeps its whole name as the slug.
function parseEpicName(name) {
  const match = String(name).match(/^epic-(\d+)-(.+)$/);
  return match ? { number: match[1], slug: match[2] } : { number: null, slug: name };
}

// Same epic when the slugs match and the numbers are equal as numbers
// (`epic-8-x` and `epic-08-x`), or both absent.
function sameEpic(entry, epic) {
  const entryNumber = entry.number === "-" ? null : entry.number;
  if (entry.slug !== epic.slug) return false;
  if (entryNumber === null || epic.number === null) return entryNumber === epic.number;
  return Number(entryNumber) === Number(epic.number);
}

// Whether the index holds an archived entry for this epic directory name.
function isArchived(root, name) {
  const epic = parseEpicName(name);
  return archivedEpics(root).some((entry) => sameEpic(entry, epic));
}

// The file content once `entry` (Markdown) is appended to the archived section,
// creating the file or the section when missing. Pure: the caller writes.
function withArchivedEntry(existing, entry) {
  if (existing === null) {
    return `# Epics\n\n${SECTION_HEADER}\n${entry}`;
  }

  const base = existing.endsWith("\n") ? existing : `${existing}\n`;

  if (base.includes(SECTION_MARKER)) {
    return `${base}\n${entry}`;
  }

  return `${base}\n${SECTION_HEADER}\n${entry}`;
}

// The live section (story 17-02): every epic on disk and every story's written
// `## Status:`, regenerated whole between the two markers. Written status, not
// proof status: a proof goes stale on every commit, a written status only when
// someone edits the story, so the file stays quiet and `doctor` can call it
// current. `epics` is handed in by the layer: [{ name, title, stories: [{
// number, title, status }] }], in the order to print.
const LIVE_START = "<!-- coding-flow:index:start -->";
const LIVE_END = "<!-- coding-flow:index:end -->";

function renderLiveSection(epics) {
  const lines = [
    LIVE_START,
    "## Live epics",
    "",
    "Generated by `ai-flow archive --refresh`; edits between these markers are replaced.",
    "Each story shows the status written in its file (`## Status:`, `—` when none);",
    "the proof-derived state comes from `ai-flow status`.",
    "",
  ];
  if (epics.length === 0) lines.push("No epic directory on disk.", "");
  for (const epic of epics) {
    const { number } = parseEpicName(epic.name);
    lines.push(`### ${number ? `Epic ${number}` : epic.name} — ${epic.title} (\`epics/${epic.name}/\`)`, "");
    if (epic.stories.length === 0) lines.push("- no story yet");
    for (const story of epic.stories) lines.push(`- ${story.number} · ${story.title} · ${story.status || "—"}`);
    lines.push("");
  }
  lines.push(LIVE_END);
  return lines.join("\n");
}

// { start, end } offsets of the live section (end past LIVE_END), null when
// absent, { broken } when one marker is missing, repeated or out of order.
function liveSectionBounds(text) {
  const start = text.indexOf(LIVE_START);
  const end = text.indexOf(LIVE_END);
  if (start < 0 && end < 0) return null;
  const repeated = text.indexOf(LIVE_START, start + 1) >= 0 || text.indexOf(LIVE_END, end + 1) >= 0;
  if (start < 0 || end < 0 || end < start || repeated) return { broken: true };
  return { start, end: end + LIVE_END.length };
}

// Whether a marker is there but the pair is unusable.
function liveSectionBroken(text) {
  const bounds = text === null ? null : liveSectionBounds(text);
  return Boolean(bounds && bounds.broken);
}

// The current live section as written, or null.
function liveSectionOf(text) {
  const bounds = text === null ? null : liveSectionBounds(text);
  return bounds && !bounds.broken ? text.slice(bounds.start, bounds.end) : null;
}

// The file content with `section` as its live section. Text outside the
// markers is kept byte for byte; without markers the section goes above the
// archived section, or at the end. Pure; throws on broken markers.
function withLiveSection(existing, section) {
  if (existing === null) return `# Epics\n\n${section}\n`;
  const bounds = liveSectionBounds(existing);
  if (bounds && bounds.broken) {
    throw new Error(`${INDEX_FILE} has a broken live section: ${LIVE_START} and ${LIVE_END} must each appear once, in that order — fix the markers by hand`);
  }
  if (bounds) return existing.slice(0, bounds.start) + section + existing.slice(bounds.end);

  const archived = existing.indexOf(SECTION_HEADER.split("\n")[0] + "\n\n" + SECTION_MARKER);
  if (archived >= 0) return `${existing.slice(0, archived)}${section}\n\n${existing.slice(archived)}`;
  const base = existing.endsWith("\n") ? existing : `${existing}\n`;
  return `${base}\n${section}\n`;
}

module.exports = {
  INDEX_FILE,
  LIVE_START,
  LIVE_END,
  indexPath,
  indexKind,
  readIndex,
  archivedEpics,
  withArchivedEntry,
  parseEpicName,
  sameEpic,
  isArchived,
  renderLiveSection,
  liveSectionOf,
  liveSectionBroken,
  withLiveSection,
};

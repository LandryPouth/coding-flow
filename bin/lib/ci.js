"use strict";

// `ai-flow ci init`: scaffolds a GitHub Actions workflow in the TARGET project
// that replays the story verification on a FRESH checkout, out of the agent's
// hands. This is the non-gameable gate: the machine's pass/fail, not the agent's
// claim. Carried by GitHub compute (free), it preserves the Claude budget.
//
// Opt-in by design: the workflow is written on demand (not in templates/, so it
// isn't installed by default on every `init`). Non-destructive: it does not
// overwrite an existing workflow without --force.

const fs = require("fs");
const path = require("path");

const { cwd, packageJson } = require("./context");
const { log, normalizePortable } = require("./util");

function workflowPath(root) {
  return path.join(root, ".github", "workflows", "coding-flow-verify.yml");
}

function workflowContent() {
  // Pin the version so the clean-room gate is reproducible: a CI run replays the
  // exact CLI the project was scaffolded with, not whatever is latest at run time.
  // Re-run `ci init --force` after an upgrade to bump it.
  const pkg = `${packageJson.name}@${packageJson.version}`;

  return `# Generated by \`ai-flow ci init\`. Replays the verification on a fresh
# environment: the non-gameable gate (the machine's pass/fail, not the agent's).
name: coding-flow verify

on:
  pull_request:
  push:
    branches: [main, master]

jobs:
  verify:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          # fetch-depth 0: a possible diff-coverage step needs the history.
          fetch-depth: 0

      - uses: actions/setup-node@v4
        with:
          node-version: 20.x

      # verify runs the validation commands DECLARED by the project
      # (config.validation.commands, then plan.md, then package.json scripts).
      # So we install the target project's dependencies if they exist.
      - name: Install project dependencies
        run: |
          if [ -f package-lock.json ]; then
            npm ci
          elif [ -f package.json ]; then
            npm install
          else
            echo "No package.json — skipping dependency install."
          fi

      # Clean-room: executes the declared validation commands and CAPTURES the
      # evidence. A story-based repo (epics/*/story-*) is verified per story via
      # \`run\`, so every story gets its own captured proof; a repo that declares
      # its commands globally instead falls back to a single \`harness verify\`.
      # Either way it fails if a command breaks or if nothing ran at all
      # ("nothing executed != verified").
      - name: Verify (execute declared validation commands)
        run: |
          if ls epics/*/story-*/ >/dev/null 2>&1; then
            npx --yes ${pkg} run
          else
            npx --yes ${pkg} harness verify
          fi

      # Gate: the latest verify evidence per story must be green.
      - name: Audit gate (no green evidence, no merge)
        run: npx --yes ${pkg} audit --check

      # The evidence stays attached to the CI run (even on failure), for the audit.
      - name: Upload evidence
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: coding-flow-evidence
          path: .coding-flow/runs/
          if-no-files-found: ignore

      # --- Diff-coverage (optional) ----------------------------------------
      # The coverage floor OF THE CHANGED CODE (not the global, inflatable
      # coverage) is the natural complement to verify. coding-flow provides the
      # hook, not a home-made runner: wire your tool here (e.g. diff-cover) onto
      # the coverage report produced by your tests.
      #
      # - name: Diff coverage floor
      #   run: |
      #     git fetch origin \${{ github.base_ref }}
      #     npx --yes diff-cover coverage.xml --compare-branch=origin/\${{ github.base_ref }} --fail-under=80
`;
}

function ciInit({ dryRun = false, force = false } = {}) {
  const target = workflowPath(cwd);
  const rel = normalizePortable(path.relative(cwd, target));
  const exists = fs.existsSync(target);

  if (exists && !force) {
    log(`CI workflow already present: ${rel} (use --force to overwrite).`);
    return { status: "skipped", path: target };
  }

  if (!dryRun) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, workflowContent());
  }

  const verb = dryRun ? "Would write" : exists ? "Overwrote" : "Wrote";
  log(`${verb} clean-room CI workflow: ${rel}`);
  log("It runs `ai-flow run` (per story) or `harness verify`, then `audit --check`, on a fresh checkout for every PR.");
  return { status: exists ? "overwritten" : "created", path: target };
}

function ciCommand({ commandArgs, flags }) {
  const subcommand = commandArgs[0] || "init";

  if (subcommand === "init") {
    ciInit({ dryRun: flags.has("--dry-run"), force: flags.has("--force") });
  } else {
    const { fail } = require("./util");
    fail(`unknown ci command "${subcommand}". Use init.`);
  }
}

module.exports = { ciCommand, workflowContent, workflowPath };

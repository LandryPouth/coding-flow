"use strict";

// `ai-flow audit`: aggregates the scattered evidences (.coding-flow/runs/*.json)
// into a durable, exportable ledger. The ledger (.coding-flow/ledger.jsonl) is
// APPEND-ONLY — one JSON line per run, never rewritten: that is the integrity
// guarantee (we don't erase the verification history). The docs/AUDIT.md export
// is the artifact we show to compliance; `--check` is the CI gate "no merge
// without the latest evidence green".

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const { cwd } = require("./context");
const { log, normalizePortable } = require("./util");
const { currentTreeToken } = require("./identity");

function runsDir(root) {
  return path.join(root, ".coding-flow", "runs");
}

function ledgerPath(root) {
  return path.join(root, ".coding-flow", "ledger.jsonl");
}

function auditExportPath(root) {
  return path.join(root, "docs", "AUDIT.md");
}

function decisionsExportPath(root) {
  return path.join(root, "docs", "DECISIONS.md");
}

// Epics/stories, read directly from disk. `audit.js` cannot go through the
// storage seam (`storage/local.js` already requires `./audit` for verify
// status — routing back through storage here would be a require cycle), so
// this walks `epics/` itself: the same shape `storage/local.js` builds, minus
// the status enrichment decisions aggregation does not need.
function listEpicStories(root) {
  const epicsRoot = path.join(root, "epics");
  const epics = [];

  if (!fs.existsSync(epicsRoot)) {
    return epics;
  }

  for (const epicEntry of fs.readdirSync(epicsRoot, { withFileTypes: true })) {
    if (!epicEntry.isDirectory()) {
      continue;
    }

    const epicDir = path.join(epicsRoot, epicEntry.name);
    const stories = [];

    for (const storyEntry of fs.readdirSync(epicDir, { withFileTypes: true })) {
      if (storyEntry.isDirectory() && storyEntry.name.startsWith("story-")) {
        stories.push({
          name: storyEntry.name,
          path: normalizePortable(path.relative(root, path.join(epicDir, storyEntry.name))),
        });
      }
    }

    epics.push({ name: epicEntry.name, stories });
  }

  return epics;
}

// STANDARD/STRICT stories carry `## Decisions` in plan.md; a QUICK/FAST
// single-file story only has story.md and usually has no Decisions section at
// all — checked second so one added by hand still surfaces.
function decisionsSourceFile(root, storyPath) {
  const dir = path.join(root, storyPath);
  for (const name of ["plan.md", "story.md"]) {
    const file = path.join(dir, name);
    if (fs.existsSync(file)) {
      return file;
    }
  }
  return null;
}

// Extracts the raw text under a `## Decisions` heading, up to the next `##`
// heading or EOF. Null when the heading is absent or the section is empty —
// most QUICK stories skip it, and that must not read as "recorded: nothing".
function extractDecisionsSection(content) {
  const lines = content.split(/\r?\n/);
  const startIndex = lines.findIndex((line) => /^##\s+Decisions\s*$/i.test(line.trim()));

  if (startIndex === -1) {
    return null;
  }

  const body = [];
  for (let i = startIndex + 1; i < lines.length; i += 1) {
    if (/^##\s+/.test(lines[i])) {
      break;
    }
    body.push(lines[i]);
  }

  const text = body.join("\n").trim();
  return text.length > 0 ? text : null;
}

// Cross-epic view of every story's recorded `## Decisions` — no new file to
// maintain by hand: the story files already are the source of truth, this only
// aggregates what is already there, on demand.
function collectDecisions(root) {
  const entries = [];

  for (const epic of listEpicStories(root)) {
    for (const story of epic.stories) {
      const file = decisionsSourceFile(root, story.path);
      if (!file) {
        continue;
      }

      const decisions = extractDecisionsSection(fs.readFileSync(file, "utf8"));
      if (!decisions) {
        continue;
      }

      entries.push({
        epic: epic.name,
        story: story.name,
        path: story.path,
        source: normalizePortable(path.relative(root, file)),
        decisions,
      });
    }
  }

  return entries;
}

function buildDecisionsMarkdown(entries) {
  const lines = [
    "# Decisions",
    "",
    "> Generated by `ai-flow audit --decisions --export`. Aggregates the `## Decisions`",
    "> sections recorded in each story's plan (or story.md), cross-epic. Edit the",
    "> story file, not this export — it is regenerated, never hand-maintained.",
    "",
  ];

  if (entries.length === 0) {
    lines.push("_No recorded decisions yet._", "");
    return lines.join("\n");
  }

  let currentEpic = null;
  for (const entry of entries) {
    if (entry.epic !== currentEpic) {
      currentEpic = entry.epic;
      lines.push(`## ${currentEpic}`, "");
    }
    lines.push(`### ${entry.story}`, "", entry.decisions, "");
  }

  return lines.join("\n");
}

// Turns a run file into a ledger entry. id = hash of the content: two passes over
// the same run give the same id, so no duplicate.
function entryFromRunFile(file, root) {
  const raw = fs.readFileSync(file, "utf8");
  const data = JSON.parse(raw);
  const id = crypto.createHash("sha256").update(raw).digest("hex").slice(0, 12);
  const type = file.endsWith("-verify.json") ? "verify" : "evidence";
  const git = data.provenance && data.provenance.git ? data.provenance.git : null;

  const ok =
    type === "verify"
      ? Boolean(data.ok)
      : Boolean(data.validation && data.validation.harnessCheck === "pass");

  let summary;
  if (type === "verify") {
    const count = data.commandsFound != null ? data.commandsFound : (data.results || []).length;
    summary = `${count} command(s) ${ok ? "passed" : "FAILED"} (${data.commandSource || "n/a"})`;
  } else {
    summary = `harness ${ok ? "pass" : "fail"}${data.risk ? `, risk ${data.risk.level}` : ""}`;
  }

  return {
    id,
    file: normalizePortable(path.relative(root, file)),
    type,
    generatedAt: data.generatedAt || null,
    ok,
    story: data.story || null,
    commandSource: data.commandSource || null,
    commit: git ? git.shortCommit || git.commit || null : null,
    branch: git ? git.branch || null : null,
    author: git && git.author ? git.author.name || null : null,
    // Working-tree content token captured with the run. Lets the gate tell a
    // proof that still describes the current code from a stale one. Absent on
    // pre-freshness or non-git evidence -> treated leniently (never stale).
    treeToken: git ? git.treeToken || null : null,
    summary,
  };
}

function collectRunEntries(root) {
  const dir = runsDir(root);

  if (!fs.existsSync(dir)) {
    return [];
  }

  const entries = [];

  for (const name of fs.readdirSync(dir).sort()) {
    if (!name.endsWith("-verify.json") && !name.endsWith("-evidence.json")) {
      continue;
    }
    try {
      entries.push(entryFromRunFile(path.join(dir, name), root));
    } catch {
      // An unreadable run does not invalidate the ledger: we ignore it.
    }
  }

  return entries;
}

function readLedger(root) {
  const file = ledgerPath(root);

  if (!fs.existsSync(file)) {
    return [];
  }

  return fs
    .readFileSync(file, "utf8")
    .split(/\r?\n/)
    .filter(Boolean)
    .map((line) => {
      try {
        return JSON.parse(line);
      } catch {
        return null;
      }
    })
    .filter(Boolean);
}

// Union of ledger + runs, deduplicated by id, sorted by date. Read view, mutates
// nothing.
function collectAll(root) {
  const byId = new Map();

  for (const entry of readLedger(root)) {
    if (entry && entry.id) {
      byId.set(entry.id, entry);
    }
  }
  for (const entry of collectRunEntries(root)) {
    if (!byId.has(entry.id)) {
      byId.set(entry.id, entry);
    }
  }

  return [...byId.values()].sort((a, b) => (a.generatedAt || "").localeCompare(b.generatedAt || ""));
}

// Appends to the ledger the runs not yet recorded. Append-only: existing lines
// are never rewritten.
function syncLedger(root, { dryRun = false } = {}) {
  const known = new Set(readLedger(root).map((entry) => entry.id));
  const added = collectRunEntries(root).filter((entry) => !known.has(entry.id));

  if (added.length > 0 && !dryRun) {
    fs.mkdirSync(path.dirname(ledgerPath(root)), { recursive: true });
    fs.appendFileSync(ledgerPath(root), `${added.map((entry) => JSON.stringify(entry)).join("\n")}\n`);
  }

  return { added };
}

// Gate: the latest VERIFY evidence per story must be green. No run = not
// verified = failure. Usable in CI for "no merge without green proof".
// A green verify is "stale" when its captured working-tree token no longer
// matches the current one: the code changed after the proof was produced. Only
// decidable when both tokens exist — otherwise (old/non-git evidence) lenient.
function isStale(entry, currentToken) {
  return Boolean(entry.ok && entry.treeToken && currentToken && entry.treeToken !== currentToken);
}

function gate(entries, { currentToken = null } = {}) {
  const verify = entries.filter((entry) => entry.type === "verify");

  if (verify.length === 0) {
    return { ok: false, reason: "no verify runs recorded", failing: [], stale: [], latest: [] };
  }

  const byStory = new Map();
  for (const entry of verify) {
    const key = entry.story || "(repo)";
    const prev = byStory.get(key);
    if (!prev || (entry.generatedAt || "") > (prev.generatedAt || "")) {
      byStory.set(key, entry);
    }
  }

  const latest = [...byStory.values()];
  const failing = latest.filter((entry) => !entry.ok);
  // A stale proof is not a passing proof: the latest green run no longer
  // describes the code being pushed, so re-verification is required.
  const stale = latest.filter((entry) => isStale(entry, currentToken));

  return { ok: failing.length === 0 && stale.length === 0, reason: null, failing, stale, latest };
}

// Latest VERIFY result per story DIRECTORY, keyed by the portable relative path
// of the story dir. `status` uses it to back a story's state on executed proof
// (a captured verify) instead of prose. Same grouping as `gate`, but normalizes a
// file-path `--story` (e.g. `.../spec.md`) down to its directory so the key
// matches the story dir that `status`/`listEpics` iterate. Read-only.
function latestVerifyByStoryDir(root) {
  const byDir = new Map(); // dirPath -> { ok, generatedAt }

  for (const entry of collectAll(root)) {
    if (entry.type !== "verify" || !entry.story) {
      continue;
    }

    const dir = entry.story.endsWith(".md")
      ? entry.story.split("/").slice(0, -1).join("/")
      : entry.story;
    const prev = byDir.get(dir);

    if (!prev || (entry.generatedAt || "") > (prev.generatedAt || "")) {
      byDir.set(dir, { ok: entry.ok, generatedAt: entry.generatedAt || "", treeToken: entry.treeToken || null });
    }
  }

  return byDir;
}

function buildAuditMarkdown(entries) {
  const lines = [
    "# Audit ledger",
    "",
    "> Generated by `ai-flow audit --export`. Chronological ledger of the evidences",
    "> (`harness verify` / `harness evidence`) captured on this repository. Source of",
    "> truth: `.coding-flow/ledger.jsonl` (append-only).",
    "",
  ];

  if (entries.length === 0) {
    lines.push("_No evidence recorded yet._", "");
    return lines.join("\n");
  }

  lines.push(
    "| Date | Type | Result | Story | Commit | Author | Source |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  );

  for (const entry of entries) {
    lines.push(
      `| ${entry.generatedAt || "n/a"} | ${entry.type} | ${entry.ok ? "✅" : "❌"} | ${
        entry.story || "—"
      } | ${entry.commit ? `\`${entry.commit}\`` : "—"} | ${entry.author || "—"} | ${
        entry.commandSource || "—"
      } |`,
    );
  }

  lines.push("");
  return lines.join("\n");
}

function audit({
  json = false,
  exportMd = false,
  check = false,
  since = null,
  dryRun = false,
  decisions = false,
} = {}) {
  const root = cwd;

  // Its own read-only mode: a cross-epic view of recorded `## Decisions`, not
  // the run-evidence ledger below. Never touches `.coding-flow/ledger.jsonl`.
  if (decisions) {
    const entries = collectDecisions(root);

    if (json) {
      log(JSON.stringify(entries, null, 2));
      return;
    }

    if (exportMd) {
      const target = decisionsExportPath(root);
      if (!dryRun) {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, buildDecisionsMarkdown(entries));
      }
      log(
        `${dryRun ? "Would export" : "Exported"} ${entries.length} decision(s) to ` +
          `${normalizePortable(path.relative(root, target))}`,
      );
      return;
    }

    if (entries.length === 0) {
      log("No recorded decisions found (`## Decisions` in plan.md / story.md).");
      return;
    }

    log(`Decisions: ${entries.length} stor${entries.length === 1 ? "y" : "ies"} with recorded decisions.`);
    log("");
    for (const entry of entries) {
      log(`${entry.epic} / ${entry.story}`);
      log(entry.decisions);
      log("");
    }
    return;
  }

  // The CI gate is read-only: it must not mutate the ledger.
  if (check) {
    let entries = collectAll(root);
    if (since) {
      entries = entries.filter((entry) => entry.generatedAt && entry.generatedAt >= since);
    }
    const result = gate(entries, { currentToken: currentTreeToken(root) });

    if (json) {
      log(JSON.stringify(result, null, 2));
    } else if (result.ok) {
      log(`Audit check passed — ${result.latest.length} story/scope(s), latest verify green and fresh.`);
    } else if (result.reason) {
      log(`Audit check FAILED — ${result.reason}.`);
    } else {
      if (result.failing.length > 0) {
        log("Audit check FAILED — latest verify is red for:");
        for (const entry of result.failing) {
          log(`- ${entry.story || "(repo)"}: ${entry.summary}`);
        }
      }
      if (result.stale.length > 0) {
        log("Audit check FAILED — latest verify is stale (code changed since the proof); re-run `ai-flow verify --story <dir>` for:");
        for (const entry of result.stale) {
          log(`- ${entry.story || "(repo)"}: verified at ${entry.commit || "?"}, no longer matches the working tree`);
        }
      }
    }

    if (!result.ok) {
      process.exitCode = 1;
    }
    return;
  }

  const sync = syncLedger(root, { dryRun });
  let entries = collectAll(root);
  if (since) {
    entries = entries.filter((entry) => entry.generatedAt && entry.generatedAt >= since);
  }

  if (exportMd) {
    const target = auditExportPath(root);
    if (!dryRun) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, buildAuditMarkdown(entries));
    }
    log(`${dryRun ? "Would export" : "Exported"} ${entries.length} entr(ies) to ${normalizePortable(path.relative(root, target))}`);
  }

  if (json) {
    log(JSON.stringify(entries, null, 2));
    return;
  }

  const passed = entries.filter((entry) => entry.ok).length;
  log(`Audit ledger: ${entries.length} entr(ies), ${passed} passed, ${entries.length - passed} failed.`);
  log(`${dryRun ? "Would append" : "Appended"} ${sync.added.length} new run(s) to ${normalizePortable(path.relative(root, ledgerPath(root)))}.`);
  if (!exportMd) {
    log("Run `ai-flow audit --export` to write docs/AUDIT.md, or `--check` to gate on the latest verify.");
  }
}

function auditCommand({ getFlagValue, flags }) {
  audit({
    json: flags.has("--json"),
    exportMd: flags.has("--export"),
    check: flags.has("--check"),
    since: getFlagValue("--since", null),
    dryRun: flags.has("--dry-run"),
    decisions: flags.has("--decisions"),
  });
}


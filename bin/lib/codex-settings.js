"use strict";

// Codex CLI's write guard: a `.codex/config.toml` permissions profile that denies
// writes to the blocked paths at the OS sandbox level (Landlock/bwrap, Seatbelt),
// not a hook. The denied list is the one the Claude guard enforces
// (`blockedPaths` in .coding-flow/harness.json, via loadPolicy) — one policy, two
// enforcement mechanisms.
//
// A custom `default_permissions` profile REPLACES Codex's built-in workspace-write
// grants, and without a broad read grant ("/" = "read") Codex cannot exec itself
// inside the sandbox — so that grant is restated here, not simplified away.
//
// config.toml is a user config file, so the merge is marker-gated: a file that
// does not START with the marker is foreign and is never touched.

const fs = require("fs");
const path = require("path");

const { cwd } = require("./context");
const { loadPolicy } = require("./guard");

const PROFILE_NAME = "coding-flow-guard";
const MARKER =
  "# generated by coding-flow — do not hand-edit; re-run `ai-flow upgrade` after changing blockedPaths in .coding-flow/harness.json";

function configPath(root = cwd) {
  return path.join(root, ".codex", "config.toml");
}

function denyEntries(blockedPaths) {
  const entries = new Set();

  // harness.json is hand-editable; a non-string entry must not crash upgrade/doctor.
  for (const glob of blockedPaths.filter((g) => typeof g === "string" && g)) {
    entries.add(glob);
    if (glob.endsWith("/**")) {
      entries.add(glob.slice(0, -3));
    }
  }

  return [...entries];
}

// JSON string escaping is valid TOML basic-string escaping for these inputs.
function renderConfig(blockedPaths) {
  const deny = denyEntries(blockedPaths)
    .map((glob) => `${JSON.stringify(glob)} = "deny"`)
    .join("\n");

  return `${MARKER}

default_permissions = "${PROFILE_NAME}"

[permissions.${PROFILE_NAME}]
description = "coding-flow: workspace write, except the harness blocked paths"

[permissions.${PROFILE_NAME}.filesystem]
"/" = "read"

[permissions.${PROFILE_NAME}.filesystem.":workspace_roots"]
"." = "write"
${deny}
`;
}

function expectedConfig(root = cwd) {
  return renderConfig(loadPolicy(root).blockedPaths);
}

// State of the file relative to what this install would write:
// "absent" | "foreign" (not ours) | "stale" (ours, out of date) | "current".
function inspectCodexSandbox(root = cwd) {
  const target = configPath(root);

  if (!fs.existsSync(target)) {
    return { state: "absent", path: target };
  }

  const existing = fs.readFileSync(target, "utf8");

  if (!existing.startsWith(MARKER)) {
    return { state: "foreign", path: target };
  }

  return { state: existing === expectedConfig(root) ? "current" : "stale", path: target };
}

// Statuses: "created", "upgraded" (ours, regenerated), "unchanged", "skipped"
// (foreign file, left byte-for-byte alone).
function ensureCodexSandbox({ dryRun = false, root = cwd } = {}) {
  const { state, path: target } = inspectCodexSandbox(root);

  if (state === "foreign") {
    return { status: "skipped", path: target };
  }

  if (state === "current") {
    return { status: "unchanged", path: target };
  }

  if (!dryRun) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, expectedConfig(root));
  }

  return { status: state === "absent" ? "created" : "upgraded", path: target };
}

module.exports = {
  ensureCodexSandbox,
  inspectCodexSandbox,
  renderConfig,
  PROFILE_NAME,
  MARKER,
};
